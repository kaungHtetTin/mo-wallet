/* Optional visual/in-browser checks. Requires Playwright and its Chromium browser. */
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync, spawn} = require('node:child_process');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const php = process.env.PHP_BINARY || 'php';
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'storage', 'testing');
fs.mkdirSync(out, {recursive:true});
let database, server, browser;
const issues=[];
function assert(value,label){if(!value) throw new Error(label);}
(async()=>{
    const result=execFileSync(php,['tests/run.php','--keep'],{cwd:root,encoding:'utf8',windowsHide:true});
    console.log(result.trim()); database=result.match(/TEST_DB=(mowallet_test_[a-f0-9]+)/)[1];
    const port=19000+Math.floor(Math.random()*1000), base=`http://127.0.0.1:${port}`;
    server=spawn(php,['-S',`127.0.0.1:${port}`,'-t','public','public/router.php'],{cwd:root,env:{...process.env,DB_DATABASE:database,APP_URL:'',SESSION_NAME:'mowallet_test_session'},stdio:'ignore',windowsHide:true});
    for(let i=0;i<50;i++){try{await fetch(base);break;}catch{await new Promise(r=>setTimeout(r,100));}}
    browser=await chromium.launch({headless:true});
    const context=await browser.newContext({viewport:{width:1440,height:900}});
    const page=await context.newPage();
    await page.emulateMedia({reducedMotion:'reduce'});
    page.on('pageerror',e=>issues.push(e.message));
    page.on('console',msg=>{if(msg.type()==='error' && !/fonts\.googleapis|fonts\.gstatic/.test(msg.text()))issues.push(msg.text());});
    await page.goto(base+'/login');
    await page.getByLabel('Email address').fill('owner@example.test');
    await page.getByLabel('Password',{exact:true}).fill('Wallet-New-2026!');
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
    await page.screenshot({path:path.join(out,'desktop-light.png'),fullPage:true});
    const overflow=()=>page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
    assert((await overflow()).scroll<=1440,'Desktop has page overflow');
    await page.getByRole('link',{name:'New transaction',exact:true}).click();
    await page.getByLabel(/^Type/).selectOption('transfer');
    assert(await page.getByLabel('Destination account book').isVisible(),'Transfer destination is not visible');
    assert(!await page.getByLabel('Business / personal').isVisible(),'Transfer shows business fields');
    await page.getByLabel(/^Amount \(MMK\)/).fill('15000');
    await page.getByLabel(/^Account book/).selectOption({label:'Bank'});
    await page.getByLabel('Destination account book').selectOption({label:'Cash'});
    await page.getByRole('button',{name:'Save transaction'}).click();
    await page.getByRole('status').filter({hasText:'Transaction saved.'}).waitFor();
    const transferRow=page.getByRole('row').filter({hasText:'15,000'});
    await transferRow.getByRole('button',{name:'Delete',exact:true}).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    assert(await transferRow.count()===1,'Cancel removed the transaction');
    await transferRow.getByRole('button',{name:'Delete',exact:true}).click();
    await page.getByRole('button',{name:'Confirm removal'}).click();
    await page.getByRole('status').filter({hasText:'Transaction removed.'}).waitFor();
    await page.goto(base+'/settings');
    await page.getByRole('button',{name:'Switch light / dark'}).click();
    assert(await page.locator('html').getAttribute('data-theme')==='dark','Theme switch failed');
    await page.setViewportSize({width:1280,height:720});
    await page.goto(base+'/reports');
    await page.screenshot({path:path.join(out,'desktop-dark.png'),fullPage:true});
    assert((await overflow()).scroll<=1280,'Dark desktop has page overflow');
    await page.setViewportSize({width:1024,height:768});
    await page.goto(base+'/');
    await page.screenshot({path:path.join(out,'tablet.png'),fullPage:true});
    assert((await overflow()).scroll<=1024,'Tablet has page overflow');
    await page.goto(base+'/settings');
    await page.getByLabel('Display density').selectOption('comfortable');
    assert(await page.locator('html').getAttribute('data-density')==='comfortable','Comfortable density failed');
    await page.getByRole('button',{name:'Switch light / dark'}).click();
    await page.setViewportSize({width:390,height:844});
    await page.goto(base+'/');
    await page.getByRole('button',{name:'Toggle navigation'}).click();
    await page.getByRole('link',{name:'Payables & receivables',exact:true}).click();
    await page.getByRole('heading',{name:'Payables & receivables',exact:true}).waitFor();
    await page.screenshot({path:path.join(out,'mobile-balances.png'),fullPage:true});
    assert((await overflow()).scroll<=390,'Mobile balances have page overflow');
    await page.getByRole('link',{name:'New unpaid balance',exact:true}).click();
    await page.screenshot({path:path.join(out,'mobile-form.png'),fullPage:true});
    assert((await overflow()).scroll<=390,'Mobile form has page overflow');
    await page.getByRole('button',{name:'မြန်မာ',exact:true}).click();
    assert(await page.locator('html').getAttribute('lang')==='my','Myanmar switch failed');
    await page.screenshot({path:path.join(out,'mobile-myanmar-form.png'),fullPage:true});
    assert((await overflow()).scroll<=390,'Myanmar form has page overflow');
    await page.setViewportSize({width:1440,height:900});
    await page.goto(base+'/reports');
    await page.screenshot({path:path.join(out,'desktop-myanmar.png'),fullPage:true});
    assert((await overflow()).scroll<=1440,'Myanmar desktop has page overflow');
    await page.getByRole('button',{name:'English',exact:true}).click();
    await page.goto(base+'/transactions');
    await page.getByLabel('Search',{exact:true}).fill('Shop sales');
    await page.getByRole('button',{name:'Apply filters',exact:true}).click();
    assert(await page.getByRole('cell',{name:'Shop sales',exact:false}).count()===1,'Search filter did not find shop sales');
    await page.goto(base+'/manage/people');
    await page.getByRole('link',{name:'Import contacts',exact:true}).click();
    await page.getByRole('heading',{name:'Import contacts',exact:true}).waitFor();
    assert(await page.getByRole('button',{name:'Choose phone contacts',exact:true}).isDisabled(),'Unsupported desktop contact picker should be disabled');
    const vcard='BEGIN:VCARD\r\nVERSION:3.0\r\nFN:Imported via browser\r\nTEL:09444444444\r\nTEL:01123456\r\nEND:VCARD\r\nBEGIN:VCARD\r\nVERSION:3.0\r\nFN:မြန်မာအဆက်အသွယ်\r\nTEL:09555555555\r\nEND:VCARD\r\nBEGIN:VCARD\r\nVERSION:3.0\r\nFN:အောင်အောင်\r\nTEL:+95 9 123456789\r\nEND:VCARD\r\n';
    await page.getByLabel('Contact file (.vcf)').setInputFiles({name:'contacts.vcf',mimeType:'text/vcard',buffer:Buffer.from(vcard)});
    await page.getByRole('button',{name:'Preview contacts',exact:true}).click();
    await page.getByRole('heading',{name:'Contact preview',exact:true}).waitFor();
    assert(await page.getByRole('checkbox',{name:'Import contact: အောင်အောင်',exact:true}).isDisabled(),'Duplicate should be disabled in preview');
    await page.getByRole('checkbox',{name:'Select all',exact:true}).uncheck();
    assert(await page.getByRole('button',{name:'Import selected contacts',exact:true}).isDisabled(),'Empty selection should disable import');
    await page.getByRole('checkbox',{name:'Import contact: Imported via browser',exact:true}).check();
    await page.screenshot({path:path.join(out,'contacts-desktop-preview.png'),fullPage:true});
    await page.getByRole('button',{name:'မြန်မာ',exact:true}).click();
    await page.getByRole('heading',{name:'အဆက်အသွယ်များ ကြိုကြည့်ရန်',exact:true}).waitFor();
    assert(new URL(page.url()).searchParams.has('draft'),'Language switch lost the import draft');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,'contacts-mobile-myanmar.png'),fullPage:true});
    assert((await overflow()).scroll<=390,'Contact preview has page overflow on mobile');
    await page.getByRole('button',{name:'English',exact:true}).click();
    assert(!await page.getByRole('checkbox',{name:'Import contact: မြန်မာအဆက်အသွယ်',exact:true}).isChecked(),'Language switching changed the contact selection');
    await page.getByRole('button',{name:'Import selected contacts',exact:true}).click();
    await page.getByRole('status').filter({hasText:'Contacts imported: 1'}).waitFor();
    assert(await page.getByRole('cell',{name:'Imported via browser',exact:false}).count()===1,'Selected contact was not imported');
    assert(await page.getByRole('cell',{name:'မြန်မာအဆက်အသွယ်',exact:false}).count()===0,'Unselected contact was imported');
    await page.goto(base+'/people/import');
    await page.screenshot({path:path.join(out,'contacts-mobile-chooser.png'),fullPage:true});
    assert((await overflow()).scroll<=390,'Contact chooser has mobile page overflow');
    // Simulates API responses only; never accesses a real device address book.
    await context.addInitScript(() => {
        Object.defineProperty(navigator,'contacts',{configurable:true,value:{select:async(props,options)=>{
            window.__contactRequest={props,options,active:navigator.userActivation.isActive};
            return [{name:['Phone picker example'],tel:['09666666666']}];
        }}});
    });
    await page.reload();
    assert(await page.getByRole('button',{name:'Choose phone contacts',exact:true}).isEnabled(),'Supported contact picker should be enabled');
    await page.getByRole('button',{name:'Choose phone contacts',exact:true}).click();
    await page.getByRole('heading',{name:'Contact preview',exact:true}).waitFor();
    assert(await page.getByRole('cell',{name:'Phone picker example',exact:true}).count()===1,'Phone picker payload did not reach preview');
    await page.getByRole('button',{name:'Discard preview & start again',exact:true}).click();
    await page.getByRole('heading',{name:'Import contacts',exact:true}).waitFor();
    await page.goto(base+'/manage/people');
    assert(await page.getByRole('cell',{name:'Phone picker example',exact:false}).count()===0,'Discarded phone contact was saved');
    assert(issues.length===0,'Browser errors: '+issues.join('; '));
    console.log('PASS: Browser flows and contacts: upload, preview, selection, duplicate skipping, language, mobile, simulated phone picker, and discard.');
})().catch(async error=>{
    console.error(error);
    const page=browser?.contexts()[0]?.pages()[0];
    if(page){await page.screenshot({path:path.join(out,'failure.png'),fullPage:true});console.error((await page.locator('main').innerText()).slice(0,1500));}
    process.exitCode=1;
}).finally(async()=>{
    await browser?.close();
    server?.kill();
    if(database) execFileSync(php,['tests/cleanup.php',database],{cwd:root,windowsHide:true});
});
